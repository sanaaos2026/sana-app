def main():
    db = sqlite3.connect(DB_PATH)
    db.row_factory = sqlite3.Row

    existing_titles = {
        r["title"] for r in db.execute(
            "SELECT title FROM tasks WHERE company_id=?", (COMPANY_ID,)
        ).fetchall()
    }

    inserted = 0
    for title, decision_id, phase_label, priority, due_date, value_note in TASKS:
        if title in existing_titles:
            continue
        task_id = "TSK" + uuid.uuid4().hex[:6].upper()
        db.execute(
            """INSERT INTO tasks
               (task_id, company_id, decision_id, title, owner_user_id, due_date,
                status, priority, phase_label, value_note)
               VALUES (?,?,?,?,?,?,?,?,?,?)""",
            (task_id, COMPANY_ID, decision_id, title, "U002", due_date,
             "لم تبدأ", priority, phase_label, value_note),
        )
        inserted += 1

    db.commit()
    db.close()
    print(f"تمت إضافة {inserted} مهمة مطلوبة جديدة لـ {COMPANY_ID}.")


if __name__ == "__main__":
    main()
